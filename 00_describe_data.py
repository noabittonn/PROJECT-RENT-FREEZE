"""Étape 4 du prof — "Go over the data and get a general characterization".

Lit les CSV ACRIS (téléchargés par `make download` du repo fitnr ou par 01_download.py)
et écrit :
    data/out/ACRIS_characterization.md     description lisible des données
    data/out/acris_doc_types.csv           nombre de documents par type
    data/out/acris_deeds_per_year.csv      deeds par année et par borough
Les tables propres pour Python / R sont ensuite produites par 02_build_transactions.py
(format Parquet, lisible avec pandas.read_parquet ou arrow::read_parquet en R).
"""
import duckdb
from config import OUT, RAW
from common import csv_view

OUT.mkdir(parents=True, exist_ok=True)
con = duckdb.connect()
csv_view(con, "acris_master", {"document_id": [], "doc_type": [],
                               "document_date": ["doc_date"],
                               "document_amt": ["doc_amount"],
                               "borough": ["recorded_borough"]})
csv_view(con, "acris_legals", {"document_id": [], "borough": [], "block": [],
                               "lot": [], "property_type": []})
csv_view(con, "acris_parties", {"document_id": [], "party_type": [], "name": [],
                                "address_1": [], "zip": []})
codes = RAW / "document_control_codes.csv"
if codes.exists():
    csv_view(con, "document_control_codes", {
        "doc_type": [], "doc_type_description": [], "class_code_description": []})
else:
    con.execute("CREATE VIEW document_control_codes AS SELECT NULL::VARCHAR doc_type, "
                "NULL::VARCHAR doc_type_description, NULL::VARCHAR class_code_description WHERE false")

date = """coalesce(try_strptime(substr(document_date,1,10),'%m/%d/%Y'),
                   try_cast(substr(document_date,1,10) AS TIMESTAMP))"""
con.execute(f"""CREATE TABLE m AS SELECT *, year({date}) AS yr,
                try_cast(document_amt AS DOUBLE) AS amt FROM acris_master""")

n = {t: con.execute(f"SELECT count(*), count(DISTINCT document_id) FROM {t}").fetchone()
     for t in ["m", "acris_legals", "acris_parties"]}
years = con.execute("SELECT min(yr), max(yr) FROM m WHERE yr BETWEEN 1960 AND 2030").fetchone()

types = con.execute("""
SELECT m.doc_type, any_value(c.doc_type_description) AS description,
       any_value(c.class_code_description) AS class, count(*) AS n_documents,
       round(100.0 * count(*) / sum(count(*)) OVER (), 2) AS pct
FROM m LEFT JOIN document_control_codes c USING (doc_type)
GROUP BY 1 ORDER BY n_documents DESC""").df()
types.to_csv(OUT / "acris_doc_types.csv", index=False)

deeds = con.execute("""
SELECT yr AS year,
       count(*) FILTER (WHERE borough='1') AS manhattan,
       count(*) FILTER (WHERE borough='2') AS bronx,
       count(*) FILTER (WHERE borough='3') AS brooklyn,
       count(*) FILTER (WHERE borough='4') AS queens,
       count(*) FILTER (WHERE borough='5') AS staten_island,
       count(*) AS total,
       round(100.0 * avg((amt <= 10)::INT), 1) AS pct_nominal_amount,
       round(median(amt) FILTER (WHERE amt > 10) / 1e3) AS median_amount_k
FROM m WHERE doc_type IN ('DEED','DEEDO') AND yr BETWEEN 2000 AND 2030
GROUP BY 1 ORDER BY 1""").df()
deeds.to_csv(OUT / "acris_deeds_per_year.csv", index=False)

parties = con.execute("""
SELECT avg(n_sellers) AS avg_sellers, avg(n_buyers) AS avg_buyers,
       avg((n_sellers = 0 OR n_buyers = 0)::INT) AS share_missing_side
FROM (SELECT document_id,
             count(*) FILTER (WHERE party_type='1') AS n_sellers,
             count(*) FILTER (WHERE party_type='2') AS n_buyers
      FROM acris_parties
      WHERE document_id IN (SELECT document_id FROM m WHERE doc_type IN ('DEED','DEEDO'))
      GROUP BY 1)""").fetchone()
llc = con.execute("""
SELECT avg(regexp_matches(upper(name), '\\bL\\.?L\\.?C\\b|\\bCORP|\\bINC\\b|\\bL\\.?P\\b|TRUST')::INT)
FROM acris_parties
WHERE document_id IN (SELECT document_id FROM m WHERE doc_type IN ('DEED','DEEDO'))""").fetchone()[0]
lots = con.execute("""SELECT avg(k) FROM (SELECT count(*) k FROM acris_legals GROUP BY document_id)""").fetchone()[0]

fmt = lambda x: "n/a" if x is None else f"{x:,.2f}"
md = f"""# ACRIS — general characterization

Source: NYC Department of Finance, ACRIS Real Property datasets (NYC Open Data),
downloaded with fitnr/acris-download. Generated by `00_describe_data.py`.

## 1. What the data are

ACRIS is the City Register: every recorded document affecting real property in
Manhattan, Bronx, Brooklyn and Queens (Staten Island is recorded by the Richmond
County Clerk and is largely absent). Three linked tables, joined on `document_id`:

| Table | One row per | Rows | Distinct documents | Key fields |
|---|---|---|---|---|
| Master | document | {n['m'][0]:,} | {n['m'][1]:,} | doc type, date, amount, borough |
| Legals | document x lot | {n['acris_legals'][0]:,} | {n['acris_legals'][1]:,} | borough, block, lot (= BBL), property type |
| Parties | document x party | {n['acris_parties'][0]:,} | {n['acris_parties'][1]:,} | party type (1 = grantor/seller, 2 = grantee/buyer), name, address |

Document dates range from {years[0]} to {years[1]}. Average lots per document: {fmt(lots)}.

## 2. Document types (top 15)

{types.head(15).to_markdown(index=False)}

Deeds (`DEED`, `DEEDO`) are the ownership transfers. Most other documents are
mortgages, satisfactions, assignments and agreements: relevant later for leverage,
but not for the buyer/seller graph.

## 3. Deeds per year

{deeds.to_markdown(index=False)}

`pct_nominal_amount` = deeds recorded at $0-$10 (intra-family, LLC restructuring,
corrections): these are not market sales and must be dropped.

## 4. Parties on deeds

- Average sellers per deed: {fmt(parties[0])}; average buyers per deed: {fmt(parties[1])}
- Share of deeds missing a buyer or seller record: {fmt(parties[2])}
- Share of deed parties that are entities (LLC, corp., LP, trust): {fmt(llc)}

## 5. Implications for the project

1. **No owner identifier.** Parties are raw names and mailing addresses. The repo
   downloads and loads the data but does not link LLCs to their ultimate owners, so
   a grouping step is still needed (HPD registrations, shared addresses).
2. **No building characteristics.** ACRIS does not say whether a lot is a
   rent-stabilized multifamily building: join on BBL to PLUTO (class, units, year built).
3. **One document can cover several lots** (portfolio sales): the price is the
   total for the document and cannot be split by building without assumptions.
4. **Nominal transfers** must be filtered out before computing prices or volumes.
"""
(OUT / "ACRIS_characterization.md").write_text(md, encoding="utf-8")
print(md)
